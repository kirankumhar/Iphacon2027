    <!-- Interactive Auto-Check & Countdown Script -->
    <script>
        (function() {
            let timeLeft = 60;
            const countdownEl = document.getElementById('countdown');
            const checkBtn = document.getElementById('btnCheckNow');
            const checkIcon = document.getElementById('checkIcon');
            const toast = document.getElementById('statusToast');
            const toastMsg = document.getElementById('statusToastMsg');

            function showToast(message, duration = 4000) {
                if (!toast || !toastMsg) return;
                toastMsg.textContent = message;
                toast.classList.add('show');
                setTimeout(() => {
                    toast.classList.remove('show');
                }, duration);
            }

            // Countdown timer
            const timer = setInterval(() => {
                timeLeft--;
                if (timeLeft <= 0) {
                    timeLeft = 60;
                    countdownEl.textContent = timeLeft + 's';
                    checkStatus(true);
                } else {
                    countdownEl.textContent = timeLeft + 's';
                }
            }, 1000);

            // Server status check
            async function checkStatus(isAuto = false) {
                if (checkIcon) checkIcon.classList.add('fa-spin');

                try {
                    const response = await fetch(window.location.href, {
                        method: 'HEAD',
                        cache: 'no-store'
                    });

                    if (response.status === 200) {
                        showToast('Portal is online! Reloading...');
                        setTimeout(() => {
                            window.location.reload();
                        }, 1200);
                        return;
                    } else {
                        if (!isAuto) {
                            showToast('Maintenance is still ongoing. Please check again shortly.');
                        }
                    }
                } catch (e) {
                    if (!isAuto) {
                        showToast('Maintenance in progress. Please check again in a few moments.');
                    }
                } finally {
                    if (checkIcon) {
                        setTimeout(() => {
                            checkIcon.classList.remove('fa-spin');
                        }, 500);
                    }
                }
            }

            if (checkBtn) {
                checkBtn.addEventListener('click', function() {
                    checkStatus(false);
                });
            }
        })();
    </script>

